function docs(available: string[], missing: string[] = []): OpsDocument[] {
  const kinds = [
    "Purchase Order",
    "Proforma Invoice",
    "Tax Invoice",
    "E-way Bill",
    "Transport Document",
    "Other",
  ] as const;
  return kinds.map((kind, index) => ({
    id: `doc-${kind}-${index}`,
    name: `${kind.replaceAll(" ", "-").toLowerCase()}.pdf`,
    kind,
    uploadedAt: available.includes(kind) ? "2026-09-08T10:00:00.000Z" : undefined,
    available: available.includes(kind) && !missing.includes(kind),
  }));
}

function step(
  id: string,
  label: string,
  status: OpsTimelineStep["status"],
  at?: string,
  actor = "Seller Ops",
  action?: string,
): OpsTimelineStep {
  return { id, label, status, at, actor, action };
}

