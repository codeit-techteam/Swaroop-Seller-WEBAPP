const ACTOR = "Operations Admin";

function activity(
  id: string,
  at: string,
  message: string,
  actor = ACTOR,
): ProcurementActivity {
  return { id, at, actor, message };
}

function timeline(
  events: Array<[string, string, string, boolean]>,
): ProcurementTimelineEvent[] {
  return events.map(([id, title, at, done], index) => ({
    id,
    title,
    description: done ? "Completed" : "Pending",
    at,
    done: done || index === 0,
  }));
}

function offer(partial: ProcurementOffer): ProcurementOffer {
  return partial;
}

