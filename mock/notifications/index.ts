const REF_PREFIXES: Record<NotificationCategory, string> = {
  "Purchase Request": "PR",
  "Offer Approved": "OFR",
  "Offer Changes Requested": "REV",
  "Inventory Reserved": "ORD",
  "Dispatch Scheduled": "SHP",
  "Shipment Delayed": "SHP",
  "Settlement Released": "INV",
  "Compliance Alert": "CMP",
  "Document Expiring": "DOC",
  "System Update": "SYS",
};

function generateNotifications(count: number): Notification[] {
  const notifications: Notification[] = [];
  const now = Date.now();

  for (let i = 0; i < count; i += 1) {
    const template = TEMPLATES[i % TEMPLATES.length]!;
    const product = PRODUCTS[i % PRODUCTS.length]!;
    const buyer = BUYERS[i % BUYERS.length]!;
    const prefix = REF_PREFIXES[template.category];
    const refNum = 8800 + count - i;
    const referenceNumber = padRef(refNum, prefix);

    const daysAgo = Math.floor(i / 3);
    const hoursAgo = (i * 37) % 24;
    const minutesAgo = (i * 13) % 60;
    const createdAt = new Date(
      now -
        daysAgo * 24 * 60 * 60 * 1000 -
        hoursAgo * 60 * 60 * 1000 -
        minutesAgo * 60 * 1000,
    ).toISOString();

    const title =
      template.category === "Offer Approved"
        ? `Offer Approved: ${product}`
        : template.title(
            template.category === "Offer Changes Requested"
              ? ""
              : `#${referenceNumber}`,
          );

    notifications.push({
      id: `notif-${String(i + 1).padStart(3, "0")}`,
      title,
      description: template.description(buyer, product),
      category: template.category,
      priority: template.priority,
      read: i > 28,
      archived: false,
      pinned: i < 2,
      referenceNumber,
      referenceLabel: template.referenceLabel
        ? `${template.referenceLabel} ${String(99 - (i % 30)).padStart(2, "0")}-${String(22 - (i % 10)).padStart(2, "0")}-A`
        : undefined,
      createdAt,
      timeline: buildTimeline(template.category, createdAt),
      attachments: buildAttachments(template.category),
      relatedOrder: buildRelatedOrder(i),
    });
  }

  return notifications.sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
  );
}

