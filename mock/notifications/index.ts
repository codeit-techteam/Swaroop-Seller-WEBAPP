function randomFrom<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)]!;
}

function padRef(num: number, prefix: string) {
  return `${prefix}-${String(num).padStart(4, "0")}`;
}

function buildTimeline(
  category: NotificationCategory,
  createdAt: string,
): NotificationTimelineEvent[] {
  const base = new Date(createdAt);
  const events: NotificationTimelineEvent[] = [
    {
      id: "1",
      title: "Notification Created",
      description: `${category} alert generated by PetroTrade ERP`,
      timestamp: createdAt,
      status: "completed",
    },
    {
      id: "2",
      title: "Seller Notified",
      description: "Alert delivered to ADMIN PANEL inbox",
      timestamp: new Date(base.getTime() - 2 * 60 * 1000).toISOString(),
      status: "completed",
    },
    {
      id: "3",
      title: "Awaiting Action",
      description: "Review and respond to this notification",
      timestamp: createdAt,
      status: "current",
    },
  ];
  return events;
}

function buildAttachments(
  category: NotificationCategory,
): NotificationAttachment[] {
  if (category === "Compliance Alert" || category === "Document Expiring") {
    return [
      {
        id: "att-1",
        name: "Compliance_Certificate.pdf",
        size: "245 KB",
        type: "PDF",
      },
      {
        id: "att-2",
        name: "Expiry_Notice.pdf",
        size: "128 KB",
        type: "PDF",
      },
    ];
  }
  if (
    category === "Purchase Request" ||
    category === "Settlement Released" ||
    category === "Dispatch Scheduled"
  ) {
    return [
      {
        id: "att-1",
        name: "Reference_Document.pdf",
        size: "312 KB",
        type: "PDF",
      },
    ];
  }
  return [];
}

function buildRelatedOrder(index: number): RelatedOrder | undefined {
  if (index % 3 !== 0) return undefined;
  return {
    id: `ord-${index}`,
    orderNumber: padRef(7700 + index, "ORD"),
    product: randomFrom(PRODUCTS),
    quantity: `${Math.floor(Math.random() * 40 + 10)} MT`,
    status: randomFrom(["Confirmed", "In Transit", "Processing", "Delivered"]),
  };
}

